/**
 * Writes src/katex.css: KaTeX's stylesheet with only its WOFF2 fonts. Every browser
 * the site supports reads WOFF2, and the WOFF/TTF copies would only make the image
 * bigger (each new layer is a slow upload to SWR). Run after updating katex:
 *   node scripts/katex-css.ts
 * src/katex-css.test.ts fails when the file is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

export function katexCss(): string {
  const require = createRequire(import.meta.url);
  const source = readFileSync(
    require.resolve("katex/dist/katex.min.css"),
    "utf8",
  );
  // src:url(fonts/X.woff2) format("woff2"),url(fonts/X.woff) format("woff"),…
  const css = source.replace(
    /src:url\((fonts\/[^)]+\.woff2)\) format\("woff2"\)(?:,url\([^)]+\) format\("[^"]+"\))*/g,
    'src:url(../node_modules/katex/dist/$1) format("woff2")',
  );
  return `/* Generated by scripts/katex-css.ts from katex/dist/katex.min.css: WOFF2 fonts only. */\n${css}\n`;
}

export const KATEX_CSS_FILE = new URL("../src/katex.css", import.meta.url);

if (import.meta.main) writeFileSync(KATEX_CSS_FILE, katexCss());
